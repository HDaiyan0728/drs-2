#!/usr/bin/env node
/*
 * Builds Reconciliation_Studio.html: index.html with engine.js and report.js inlined,
 * so the app can be emailed or opened from disk as a single file.
 * (SheetJS, Chart.js and ExcelJS are still loaded from cdnjs; see README "Offline use".)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const inline = f => `<script>\n${read(f).replace(/<\/script/gi, '<\\/script')}\n</script>`;
let html = read('index.html');
for (const f of ['engine.js', 'report.js']) {
  const tag = `<script src="./${f}"></script>`;
  if (!html.includes(tag)) throw new Error(`index.html no longer references ${f}`);
  html = html.replace(tag, () => inline(f));
}
html = html.replace('<head>', '<head>\n<!-- Generated by scripts/build-standalone.js from index.html, engine.js and report.js. Do not edit by hand. -->');
fs.writeFileSync(path.join(root, 'Reconciliation_Studio.html'), html);
console.log('Wrote Reconciliation_Studio.html (' + Math.round(html.length / 1024) + ' KB)');
